/*
 * 实验二 6: 观察复合赋值后的 a 值：int a=2; a+=a; a-=2; a*=2+3; a/=a+a;
 *
 * 知识点：复合赋值、整数除法、表达式求值。
 * 解题思路：跟踪同一变量每次赋值后的值，注意最后一步会截掉小数部分。
 * 代码逻辑：a 依次变成 4、2、10，最后做 10/20 的整数除法，输出 0。
 */
#include <stdio.h>

int main(void)
{
    int a = 2;
    a += a;     // a = 4
    a -= 2;     // a = 2
    a *= 2 + 3; // a = 10
    // a /= a + a -> a/(a+a) = 10/20 = 0
    a /= a + a;
    printf("%d\n", a);
    return 0;
}
