/*
 * 实验三 8: 输出 x,y,z（1.414,1.732,2.712），域宽6位、小数位2位。
 *
 * 知识点：最小字段宽度、小数位数、显示对齐。
 * 解题思路：用 %6.2f 同时指定至少六个字符宽和两位小数。
 * 代码逻辑：按给定值初始化三个 double，再用同一格式打印它们。
 */
#include <stdio.h>

int main(void)
{
    double x = 1.414, y = 1.732, z = 2.712;
    printf("%6.2f %6.2f %6.2f\n", x, y, z);
    return 0;
}
