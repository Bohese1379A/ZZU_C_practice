/*
 * 实验三 5: 将 60,61,62,63 赋给 d1..d4，显示相应 ASCII 字符。
 *
 * 知识点：字符编码、printf 的 %c 格式。
 * 解题思路：把给定整数当作字符码，用字符格式解释它们。
 * 代码逻辑：按照程序中的十进制值 60 到 63 逐个输出对应字符。
 */
#include <stdio.h>

int main(void)
{
    int d1 = 60, d2 = 61, d3 = 62, d4 = 63;
    printf("%c %c %c %c\n", d1, d2, d3, d4);
    return 0;
}
