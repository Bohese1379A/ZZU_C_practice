/*
 * 实验五 3：计算级数 1 - 1/5 + 1/10 - 1/17 + ...，要求最后一项的绝对值小于 1e-5。
 *
 * 知识点：交错级数、浮点绝对值、循环停止条件。
 * 解题思路：先取题面首项 1，从第二项起按 n 的奇偶确定符号，分母为 n*n+1。
 * 代码逻辑：逐项累加，加入第一项绝对值低于阈值的项后结束并输出总和。
 */
#include <math.h>
#include <stdio.h>

int main(void)
{
    double sum = 1.0; // 首项按题面给出的 1 取值，通项从第二项开始使用。
    for (int n = 2; ; ++n)
    {
        double term = (n % 2 == 0 ? -1.0 : 1.0) / ((double)n * n + 1.0);
        sum += term;
        if (fabs(term) < 1e-5) // 大小比较用绝对值，负项也按同一标准处理。
            break;
    }
    printf("%.10f\n", sum);
    return 0;
}
