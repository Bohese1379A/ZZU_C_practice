/*
 * 实验八 1: 将一维数组a[9]中各元素值按行的顺序放入二维数组b[3×3]。
 *
 * 知识点：行优先排列、一维与二维下标关系。
 * 解题思路：每行有三列，第 i 行第 j 列在一维数组中的下标是 i*3+j。
 * 代码逻辑：用双层循环填充 3×3 数组，再按行输出。
 */
#include <stdio.h>

int main(void)
{
    int a[9] = {1, 2, 3, 4, 5, 6, 7, 8, 9};
    int b[3][3];
    
    // 按行顺序填充二维数组
    for (int i = 0; i < 3; i++)
    {
        for (int j = 0; j < 3; j++)
        {
            b[i][j] = a[i * 3 + j]; // 前 i 行共有 i*3 项，再偏移 j 项。
        }
    }
    
    // 输出结果
    printf("二维数组b[3×3]：\n");
    for (int i = 0; i < 3; i++)
    {
        for (int j = 0; j < 3; j++)
        {
            printf("%4d", b[i][j]);
        }
        printf("\n");
    }
    
    return 0;
}
