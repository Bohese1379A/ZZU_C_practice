/*
 * 实验六 4: 百钱买百鸡问题。
 *
 * 知识点：枚举、整除与取余、不定方程。
 * 解题思路：枚举公鸡和母鸡的数量，由总数算出鸡雏，再验证总价。
 * 代码逻辑：只有鸡雏数为 3 的倍数才做整数除法，输出同时满足总只数和总价的组合。
 */
#include <stdio.h>

int main(void)
{
    for (int x = 0; x <= 20; x++)     // 公鸡
        for (int y = 0; y <= 33; y++) // 母鸡
        {
            int z = 100 - x - y;
            // 先保证鸡雏为三只一组，再用整数除法精确计算金额。
            if (z >= 0 && z % 3 == 0 && 5 * x + 3 * y + z / 3 == 100)
            {
                printf("cock=%d hen=%d chick=%d\n", x, y, z);
            }
        }
    return 0;
}
